"""Phase 2D analysis: Self-Monitor performance with correct, incorrect and no prior.

    python analysis/p2d_monitor_prior.py
"""

from p2_common import INK2, P2, md_table, plt, ratio_bootstrap, save

import numpy as np
import pandas as pd

from splitmind.metrics.metacognition import evaluate

D = P2 / "monitor_prior"
P = "world_change_probability"
MON = {"h0.05": ("Prior h = 0.05", "#b7d3f3", "-", "o"),
       "h0.1": ("Prior h = 0.10", "#5d9be3", "-", "s"),
       "h0.3": ("Prior h = 0.30", "#1a4f91", "-", "^"),
       "inferred": ("No prior (inferred h)", "#6250d6", "-", "D"),
       "smn": ("Naive monitor", "#8a8984", "--", "x")}


def prior_kind(mon, p):
    if not mon.startswith("h"):
        return {"inferred": "no prior", "smn": "naive"}[mon]
    h = float(mon[1:])
    return "correct" if np.isclose(h, p) else ("underestimate" if h < p else "overestimate")


def counts(steps, mon):
    s, c, gt = steps[f"{mon}_state"], steps[f"{mon}_confidence"], steps["gt_label"]
    g = steps.assign(correct=(s == gt).astype(int), one=1, knows=(s == "KNOWS").astype(int),
                     notknows=(gt != "KNOWS").astype(int),
                     falsecert=((gt != "KNOWS") & (s == "KNOWS")).astype(int),
                     conflict=(gt == "HAS_CONFLICT").astype(int),
                     detected=((gt == "HAS_CONFLICT") & (s == "HAS_CONFLICT")).astype(int),
                     critical=((gt == "HAS_CONFLICT") & (s == "KNOWS") & (c >= 0.8)).astype(int))
    return g.groupby(["latency", P, "strategy", "seed"])[
        ["correct", "one", "knows", "notknows", "falsecert", "conflict", "detected", "critical"]].sum().reset_index()


def main():
    steps = pd.read_csv(D / "steps.csv")
    episodes = pd.read_csv(D / "episodes.csv")
    rows = []
    for mon in MON:
        c = counts(steps, mon)
        for (lat, p), g in c.groupby(["latency", P]):
            st = steps[(steps.latency == lat) & (steps[P] == p)]
            ev = evaluate(st.gt_label.tolist(), st[f"{mon}_state"].tolist(), st[f"{mon}_confidence"].tolist())
            r = {"monitor": mon, "prior": prior_kind(mon, p), "latency": lat, P: p,
                 "macro_f1": ev["macro_f1"], "ece": ev["ece"], "n_steps": ev["n"]}
            for metric, num, den in [("accuracy", "correct", "one"), ("false_certainty", "falsecert", "notknows"),
                                     ("knows_rate", "knows", "one"), ("conflict_detection", "detected", "conflict"),
                                     ("critical_failure", "critical", "conflict")]:
                pt, lo, hi = ratio_bootstrap(g[num], g[den], n_boot=1000)
                r.update({metric: pt, f"{metric}_lo": lo, f"{metric}_hi": hi})
            rows.append(r)
    res = pd.DataFrame(rows)
    res.to_csv(D / "monitor_summary.csv", index=False)

    metrics = [("accuracy", "Accuracy"), ("false_certainty", "False certainty\nP(KNOWS | not KNOWS)"),
               ("knows_rate", "Rate of KNOWS"), ("conflict_detection", "Conflict detection\nP(HAS_CONFLICT | conflict)"),
               ("ece", "Calibration error (ECE)")]
    ps = sorted(res[P].unique())
    lats = sorted(res.latency.unique())
    fig, axes = plt.subplots(len(ps), len(metrics), figsize=(15, 3.0 * len(ps)), squeeze=False)
    for i, p in enumerate(ps):
        for j, (m, lab) in enumerate(metrics):
            ax = axes[i, j]
            for mon, (name, col, ls, mk) in MON.items():
                t = res[(res.monitor == mon) & (res[P] == p)].sort_values("latency")
                x = [lats.index(v) for v in t.latency]
                correct = mon.startswith("h") and np.isclose(float(mon[1:]), p)
                kw = dict(color=col, linestyle=ls, marker=mk, markeredgecolor="white",
                          linewidth=3.2 if correct else 1.8, label=name + (" (correct)" if correct else ""))
                if f"{m}_lo" in t:
                    ax.errorbar(x, t[m], yerr=[t[m] - t[f"{m}_lo"], t[f"{m}_hi"] - t[m]], capsize=2,
                                elinewidth=0.8, **kw)
                else:
                    ax.plot(x, t[m], **kw)
            ax.set_xticks(range(len(lats)), [str(v) for v in lats])
            ax.set_ylim(-0.03, 1.03)
            if i == 0:
                ax.set_title(lab, fontsize=9.5)
            if i == len(ps) - 1:
                ax.set_xlabel("Latency d")
            if j == 0:
                ax.set_ylabel(f"true p = {p:g}")
            if j == len(metrics) - 1:
                ax.legend(fontsize=7, loc="upper left")
    fig.suptitle("Self-Monitor with correct, wrong and no prior on the world change rate "
                 "(thick line = correct prior; pooled over strategies; 95% cluster-bootstrap CIs)", fontsize=10.5)
    fig.tight_layout()
    save(fig, D, "D1_monitor_prior")

    lines = ["# Phase 2D tables (generated by analysis/p2d_monitor_prior.py)\n"]
    show = ["accuracy", "macro_f1", "false_certainty", "knows_rate", "conflict_detection", "critical_failure", "ece"]
    for p in ps:
        t = res[res[P] == p].set_index(["latency", "monitor"])[["prior"] + show]
        lines.append(f"## True world change probability p = {p:g}\n\n" + md_table(t) + "\n")
    agg = res[res.latency > 0].groupby("prior")[show].mean()
    lines.append("## Mean over p and latencies d > 0, grouped by prior type\n\n" + md_table(agg) + "\n")
    agg0 = res[res.latency == 0].groupby("prior")[show].mean()
    lines.append("## Mean over p at d = 0, grouped by prior type\n\n" + md_table(agg0) + "\n")
    hz = episodes.groupby([P, "latency"]).inferred_hazard_final.agg(["mean", "std"])
    lines.append("## No-prior monitor: estimated hazard at episode end\n\n" + md_table(hz) + "\n")
    gtmix = steps.groupby(["latency", P]).gt_label.value_counts(normalize=True).unstack(fill_value=0)
    lines.append("## Ground-truth label mix\n\n" + md_table(gtmix) + "\n")
    (D / "tables.md").write_text("\n".join(lines), encoding="utf-8")
    print("  tables.md")


if __name__ == "__main__":
    main()
